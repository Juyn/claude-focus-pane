#!/usr/bin/env python3
"""Bakes the cat sheets into hooks/register.tsx, between the sprite markers.

The hooks module has no image decoder and reads no file while drawing, so the
sheets ride in the source: a palette, and one string a frame, one character a
pixel (`.` is transparent). Run it again whenever a sheet changes.

Two sheets are baked. assets/cat-sheet.png, 32x24 frames, is drawn in half
blocks, one pixel a half cell. assets/v2-64x36/cat-sheet.png, 64x36 frames, is
squeezed to 64x24 here and drawn in quadrants, four pixels a cell: twice the
detail across at the same size on screen. (Sextants would keep all 36 rows,
but a Raster cell takes no character beyond the BMP.)
"""
import json, os, subprocess

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LETTERS = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'


def bake(manifest, prefix, clips_name):
    sheet = json.load(open(manifest))
    width, height = sheet['frameWidth'], sheet['frameHeight']
    across = sheet['columns'] * width
    squeeze = []
    if (width, height) == (64, 36):
        height = 24
        squeeze = ['-filter', 'point', '-resize', f"{across}x{sheet['rows'] * height}!"]
    raw = subprocess.run(
        ['magick', os.path.join(os.path.dirname(manifest), sheet['image']), *squeeze, '-depth', '8', 'rgba:-'],
        capture_output=True, check=True).stdout
    assert len(raw) == across * sheet['rows'] * height * 4, f'{manifest}: not the size its manifest says'
    palette = []

    def letter(x, y):
        at = (y * across + x) * 4
        r, g, b, a = raw[at:at + 4]
        if a < 128:
            return '.'
        color = f'{r:02x}{g:02x}{b:02x}'
        if color not in palette:
            palette.append(color)
        return LETTERS[palette.index(color)]

    out = [f'const {clips_name} = {{']
    count = 0
    for one in sheet['animations']:
        out.append(f"  {one['name']}: {{")
        out.append(f"    ms: {one['frameDurationMs']},")
        out.append('    frames: [')
        for k in range(one['frames']):
            frame = ''.join(letter(k * width + x, one['row'] * height + y) for y in range(height) for x in range(width))
            out.append(f"      '{frame}',")
            count += 1
        out += ['    ],', '  },']
    out.append('} as const')
    head = [f'const {prefix}_W = {width}', f'const {prefix}_H = {height}',
            f"const {prefix}_INK = '{LETTERS[:len(palette)]}'",
            f'const {prefix}_PALETTE = [' + ', '.join(f'0x{c}' for c in palette) + ']']
    print(f'{clips_name}: {count} frames of {width}x{height}, {len(palette)} colors')
    return head + out


lines = ['// <sprites> generated by scripts/build-sprites.py from the sheets under assets/ — do not edit']
lines += bake(os.path.join(root, 'assets', 'cat-sheet.json'), 'SPRITE', 'CLIPS')
lines += bake(os.path.join(root, 'assets', 'v2-64x36', 'cat-sheet.json'), 'FINE', 'FINE_CLIPS')
lines.append('// </sprites>')

path = os.path.join(root, 'hooks', 'register.tsx')
source = open(path, encoding='utf-8').read()
start, end = source.index('// <sprites>'), source.index('// </sprites>') + len('// </sprites>')
open(path, 'w', encoding='utf-8').write(source[:start] + '\n'.join(lines) + source[end:])
