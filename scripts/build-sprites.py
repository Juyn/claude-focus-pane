#!/usr/bin/env python3
"""Bakes assets/cat-sheet.png into hooks/register.tsx, between the sprite markers.

The hooks module has no image decoder and reads no file while drawing, so the
sheet rides in the source: a palette, and one string a frame, one character a
pixel (`.` is transparent). Run it again whenever the sheet changes.

A sheet of 32x24 frames is drawn in half blocks, one pixel a half cell. One of
64x36 frames is squeezed to 64x24 here and drawn in quadrants, four pixels a
cell: twice the detail across at the same size on screen. (Sextants would keep
all 36 rows, but a Raster cell takes no character beyond the BMP.)
"""
import json, os, subprocess, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
manifest = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'assets', 'cat-sheet.json')
sheet = json.load(open(manifest))
width, height = sheet['frameWidth'], sheet['frameHeight']
across = sheet['columns'] * width
squeeze = []
if (width, height) == (64, 36):
    height = 24
    squeeze = ['-filter', 'point', '-resize', f"{across}x{sheet['rows'] * height}!"]
raw = subprocess.run(
    ['magick', os.path.join(os.path.dirname(os.path.abspath(manifest)), sheet['image']), *squeeze, '-depth', '8', 'rgba:-'],
    capture_output=True, check=True).stdout
assert len(raw) == across * sheet['rows'] * height * 4, 'the sheet is not the size its manifest says'

LETTERS = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'
palette = []


def letter(x, y):
    at = (y * across + x) * 4
    r, g, b, a = raw[at:at + 4]
    if a < 128:
        return '.'
    color = f'#{r:02x}{g:02x}{b:02x}'
    if color not in palette:
        palette.append(color)
    return LETTERS[palette.index(color)]


clips = []
for one in sheet['animations']:
    frames = []
    for k in range(one['frames']):
        frames.append(''.join(
            letter(k * width + x, one['row'] * height + y) for y in range(height) for x in range(width)))
    clips.append((one['name'], one['frameDurationMs'], frames))

out = ['// <sprites> generated by scripts/build-sprites.py from assets/cat-sheet.png — do not edit',
       f'const SPRITE_W: number = {width}', f'const SPRITE_H: number = {height}',
       f"const SPRITE_INK = '{LETTERS[:len(palette)]}'",
       'const SPRITE_PALETTE = [' + ', '.join(f'0x{c[1:]}' for c in palette) + ']',
       'const CLIPS = {']
for name, ms, frames in clips:
    out.append(f'  {name}: {{')
    out.append(f'    ms: {ms},')
    out.append('    frames: [')
    out += [f"      '{frame}'," for frame in frames]
    out.append('    ],')
    out.append('  },')
out += ['} as const', '// </sprites>']

path = os.path.join(root, 'hooks', 'register.tsx')
source = open(path, encoding='utf-8').read()
start, end = source.index('// <sprites>'), source.index('// </sprites>') + len('// </sprites>')
open(path, 'w', encoding='utf-8').write(source[:start] + '\n'.join(out) + source[end:])
print(f'{sum(len(f) for _, _, f in clips)} frames, {len(palette)} colors')
